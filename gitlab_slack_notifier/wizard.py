"""`gitlab-slack-notifier init`: interactive setup, checking each credential as it is entered."""

from __future__ import annotations

import getpass
import json
import os
import tomllib
from pathlib import Path
from typing import Callable

from .clients import GitLab, Slack, YouTrack
from .http import ApiError
from .paths import CONFIG_FILE, SECRETS_FILE, write_secrets

GITLAB_TOKEN_HELP = "GitLab → avatar → Edit profile → Access tokens → Add new token, scope `read_api`"
SLACK_BOT_HELP = (
    "Shared bot token (xoxb-…) of your team's Slack app, with scopes chat:write and users:read.email.\n"
    "  Ask whoever installed the app, or see the README to create one."
)
WORKFLOW_HELP = (
    "Slack → Tools → Workflow Builder → New workflow → Start from a webhook, add a `text` variable,\n"
    "  step 'Send a message to a person' (you) with body = text, Publish, copy the /triggers/ URL."
)
YOUTRACK_TOKEN_HELP = "YouTrack → Profile → Account Security → New token (scope YouTrack)"


class Prompter:
    """Thin wrapper around input()/getpass() so the wizard can be tested."""

    def __init__(self, ask: Callable[[str], str] = input, secret: Callable[[str], str] = getpass.getpass):
        self._ask = ask
        self._secret = secret

    def text(self, question: str, default: str = "") -> str:
        suffix = f" [{default}]" if default else ""
        return self._ask(f"{question}{suffix}: ").strip() or default

    def secret(self, question: str, default: str = "") -> str:
        suffix = " [keep current]" if default else ""
        return self._secret(f"{question}{suffix}: ").strip() or default

    def yes(self, question: str, default: bool = True) -> bool:
        answer = self._ask(f"{question} [{'Y/n' if default else 'y/N'}]: ").strip().lower()
        return default if not answer else answer.startswith(("y", "o"))

    def choice(self, question: str, options: list[str], default: int = 1) -> int:
        for i, opt in enumerate(options, 1):
            print(f"  {i}. {opt}")
        while True:
            answer = self.text(question, str(default))
            if answer.isdigit() and 1 <= int(answer) <= len(options):
                return int(answer)


def _toml_str(value: str) -> str:
    return json.dumps(value)  # a JSON string is a valid TOML basic string


def render_config(gitlab_url: str, slack_channel: str, projects: list[str], youtrack_url: str) -> str:
    lines = [
        "# Generated by `gitlab-slack-notifier init`. All options: config.example.toml in the repo.",
        f"gitlab_url = {_toml_str(gitlab_url)}",
        "",
        "# Slack channel ID (C…) or your member ID (U…) for DMs; unused with a webhook / workflow URL.",
        f"slack_channel = {_toml_str(slack_channel)}",
        "",
        "# Projects to watch for new MRs (full path or numeric ID).",
        "watched_projects = [",
        *(f"  {_toml_str(p)}," for p in projects),
        "]",
        "",
        "# quiet_hours = \"19:00-08:30\"   # hold notifications, deliver them when the period ends",
        "# ignore_authors = [\"renovate-bot\"]",
    ]
    if youtrack_url:
        lines += ["", f"youtrack_url = {_toml_str(youtrack_url)}"]
    return "\n".join(lines) + "\n"


def _gitlab_email(user: dict) -> str:
    return user.get("email") or user.get("commit_email") or user.get("public_email") or ""


def _ask_gitlab(p: Prompter, env: dict) -> tuple[str, str, dict]:
    url = p.text("GitLab URL", env.get("GITLAB_URL") or "https://gitlab.com").rstrip("/")
    print(f"  {GITLAB_TOKEN_HELP}")
    token = env.get("GITLAB_TOKEN", "")
    while True:
        token = p.secret("GitLab token", token)
        try:
            user = GitLab(url, token).current_user()
            print(f"  ✓ Connected as @{user['username']}")
            return url, token, user
        except ApiError as e:
            print(f"  ✗ {e}")
            token = ""
            if not p.yes("Retry?"):
                raise SystemExit(1) from None
            url = p.text("GitLab URL", url).rstrip("/")


def _ask_slack(p: Prompter, env: dict, email: str, current_channel: str = "") -> tuple[dict, str]:
    """Returns (secrets, slack_channel) once a test message went through."""
    modes = [
        "Team Slack app (bot token) — recommended, DMs you",
        "Workflow Builder URL — no app needed (paid Slack plans)",
        "Incoming webhook URL",
    ]
    default = 2 if env.get("SLACK_WORKFLOW_URL") else 3 if env.get("SLACK_WEBHOOK_URL") else 1
    while True:
        print("How should notifications reach you on Slack?")
        mode = p.choice("Choice", modes, default)
        secrets: dict[str, str] = {}
        channel = ""
        try:
            if mode == 1:
                print(f"  {SLACK_BOT_HELP}")
                token = p.secret("Slack bot token", env.get("SLACK_BOT_TOKEN", ""))
                secrets["SLACK_BOT_TOKEN"] = token
                if email:
                    try:
                        channel = Slack.lookup_user_id(token, email)
                        print(f"  ✓ Found your Slack account ({email}): {channel}")
                    except ApiError as e:
                        print(f"  ✗ {e}")
                if not channel:
                    channel = p.text(
                        "Your Slack member ID (Profile → ⋮ → Copy member ID) or a channel ID", current_channel
                    )
                slack = Slack(bot_token=token, channel=channel)
            elif mode == 2:
                print(f"  {WORKFLOW_HELP}")
                secrets["SLACK_WORKFLOW_URL"] = p.secret("Workflow URL", env.get("SLACK_WORKFLOW_URL", ""))
                slack = Slack(workflow_url=secrets["SLACK_WORKFLOW_URL"])
            else:
                secrets["SLACK_WEBHOOK_URL"] = p.secret("Webhook URL", env.get("SLACK_WEBHOOK_URL", ""))
                slack = Slack(webhook_url=secrets["SLACK_WEBHOOK_URL"])
            slack.post(":wave: GitLab notifier is connected.")
            print("  ✓ Test message sent, check Slack.")
            return secrets, channel
        except (ApiError, ValueError) as e:
            print(f"  ✗ {e}")
            if not p.yes("Retry?"):
                raise SystemExit(1) from None
            default = mode


def _ask_projects(p: Prompter, gl: GitLab, current: list[str]) -> list[str]:
    try:
        candidates = gl.recent_projects()
    except ApiError:
        candidates = []
    candidates = list(dict.fromkeys(current + candidates))[:15]
    print("Projects to watch for new MRs (you always get your to-dos and activity on your own MRs).")
    if candidates:
        for i, path in enumerate(candidates, 1):
            print(f"  {i}. {path}")
        answer = p.text("Numbers (e.g. 1,3), extra paths, or empty for none", ",".join(
            str(candidates.index(c) + 1) for c in current if c in candidates
        ))
    else:
        answer = p.text("Project paths, comma-separated (empty for none)", ",".join(current))
    chosen = []
    for item in filter(None, (s.strip() for s in answer.split(","))):
        if item.isdigit() and 1 <= int(item) <= len(candidates):
            chosen.append(candidates[int(item) - 1])
        elif not item.isdigit():
            chosen.append(item)
    return list(dict.fromkeys(chosen))


def _ask_youtrack(p: Prompter, env: dict, current_url: str) -> tuple[str, str]:
    if not p.yes("Also get YouTrack notifications?", default=bool(env.get("YOUTRACK_TOKEN"))):
        return "", ""
    url = p.text("YouTrack URL", env.get("YOUTRACK_URL") or current_url).rstrip("/")
    print(f"  {YOUTRACK_TOKEN_HELP}")
    token = env.get("YOUTRACK_TOKEN", "")
    while True:
        token = p.secret("YouTrack token", token)
        try:
            me = YouTrack(url, token).me()
            print(f"  ✓ Connected as {me.get('login')}")
            return url, token
        except ApiError as e:
            print(f"  ✗ {e}")
            token = ""
            if not p.yes("Retry?"):
                return "", ""


def run(home: Path, p: Prompter | None = None, env: dict | None = None) -> bool:
    """Interactive setup. Returns True when the user wants the background service installed."""
    p = p or Prompter()
    env = dict(os.environ if env is None else env)
    config_path, secrets_path = home / CONFIG_FILE, home / SECRETS_FILE
    print(f"Setting up gitlab-slack-notifier in {home}\n")

    current: dict = {}
    if config_path.exists():
        try:
            current = tomllib.loads(config_path.read_text())
        except tomllib.TOMLDecodeError:
            pass
        if not p.yes(f"{config_path} exists. Reconfigure (current values are offered as defaults)?"):
            return False
    if current.get("gitlab_url"):
        env.setdefault("GITLAB_URL", current["gitlab_url"])

    url, token, user = _ask_gitlab(p, env)
    print()
    slack_secrets, channel = _ask_slack(p, env, env.get("SLACK_EMAIL") or _gitlab_email(user), current.get("slack_channel", ""))
    print()
    projects = _ask_projects(p, GitLab(url, token), list(current.get("watched_projects", [])))
    print()
    yt_url, yt_token = _ask_youtrack(p, env, current.get("youtrack_url", ""))

    home.mkdir(parents=True, exist_ok=True)
    config_path.write_text(render_config(url, channel, projects, yt_url))
    write_secrets(secrets_path, {"GITLAB_TOKEN": token, **slack_secrets, "YOUTRACK_TOKEN": yt_token})
    print(f"\n✓ Wrote {config_path}\n✓ Wrote {secrets_path} (readable by you only)")
    print("The first run records what already exists and sends nothing; later runs notify what's new.\n")
    return p.yes("Start it in the background now, and at every boot?")
